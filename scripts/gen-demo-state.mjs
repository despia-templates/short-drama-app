//
//  scripts/gen-demo-state.mjs — regenerate Components/parts/DemoSeed.dsx from the LIVE api.
//
//  WHY. The native lanes are exercised on simulators and devices where no origin may be
//  reachable, and a layout pass needs every screen PAINTED to be judged. The stale-then-fresh
//  architecture already gives each screen one seam — `block.data ?? global.cacheX` — so
//  seeding those caches once lights up the whole app with SHAPE-TRUE data. Hand-written
//  fixtures drift; these are captured from the real endpoints and trimmed, so a payload
//  field the screens read can never be missing. Article 7: the seed runs ONLY off web and
//  ONLY off the App Store channel, sets `global.demoSeeded`, and Home names the state with
//  a visible pill.
//
//  Regen: with `npm run serve` up —  node scripts/gen-demo-state.mjs
//
const BASE = process.env.BASE ?? "http://localhost:8787";
const get = async (p) => {
  const r = await fetch(`${BASE}${p}`, { headers: { "user-agent": "Mozilla/5.0 (gen-demo)" } });
  if (!r.ok) throw new Error(`${p} → ${r.status}`);
  return r.json();
};

const home = await get("/catalog/home");
home.hero = home.hero.slice(0, 3);
home.latest = home.latest.slice(0, 6);
home.trending = home.trending.slice(0, 6);
home.shelves = (home.shelves ?? []).slice(0, 2).map((s) => ({ ...s, items: (s.items ?? []).slice(0, 4) }));

const browse = await get("/catalog/browse/all");
browse.items = browse.items.slice(0, 8);

const detail = await get(`/catalog/show/${home.latest[0].id}`);
detail.episodes = detail.episodes.slice(0, 12);
detail.related = (detail.related ?? []).slice(0, 3);

const feed = await get("/catalog/discover");
feed.cards = (feed.cards ?? []).slice(0, 3);

const catalog = await get("/store/catalog");

// Authenticated shapes carry no secrets worth capturing — they are DEMO values by
// construction, so the unauthenticated shapes are hand-held to the server's wire shape.
const wallet = { coins: 320, bonus: 45, vip: false, vipUntil: null };
const cont = { rows: home.latest.slice(0, 3).map((s, i) => ({
  show: s.id, idx: i + 1, episode: `${s.id}-ep${i + 1}`, title: s.title, poster: s.poster, pct: [64, 28, 91][i],
})) };
const favs = { rows: home.latest.slice(0, 4).map((s) => ({ show: s.id, title: s.title, poster: s.poster, genre: s.genre, episodes: s.episodes })) };
const inbox = { rows: [{ id: "demo-1", title: "The contract ends — but the marriage might not.", at: "2026-08-28", read: false }] };
const rewards = { streak: 2, checkedToday: false, adsToday: 0, adCap: 10, wheelToday: 0, tasks: [] };
const ledger = { rows: [
  { id: "d1", kind: "bonus", label: "Daily check-in", amount: 5, at: "2026-08-30", expires: "2026-09-06" },
  { id: "d2", kind: "coin", label: "Episode unlocked", amount: -45, at: "2026-08-30", expires: null },
] };

const js = (v) => JSON.stringify(v);
const dsx = `<!-- GENERATED by scripts/gen-demo-state.mjs — do not hand-edit; regenerate against the
     live origin. OFFLINE DEMO SEED for the NATIVE TEST lanes (Article 7, named in the UI):
     when no data has ever arrived and this is neither the web nor an App Store install, the
     app paints these captured payloads through the SAME stale-then-fresh caches every screen
     already reads. The moment a real response lands, block.data wins and this is invisible. -->
<stack width="0" height="0" on:appear="dsx.action.seed()">
  <head>
    <action as="seed">
      if (os == 'web') { return }
      if (env == 'appstore') { return }
      if (global.cacheHome != null) { return }
      global.cacheHome = ${js(home)}
      global.cacheContinue = ${js(cont)}
      global.cacheBrowse = ${js(browse)}
      global.cacheShow = ${js(detail)}
      global.cacheDiscover = ${js(feed)}
      global.cacheCatalog = ${js(catalog)}
      global.cacheWallet = ${js(wallet)}
      global.cacheFavs = ${js(favs)}
      global.cacheInbox = ${js(inbox)}
      global.cacheRewards = ${js(rewards)}
      global.cacheLedger = ${js(ledger)}
      global.demoSeeded = true
    </action>
  </head>
</stack>
`;
import { writeFileSync } from "node:fs";
writeFileSync("Components/parts/DemoSeed.dsx", dsx);
console.log(`[gen-demo-state] DemoSeed.dsx — home ${home.latest.length} shows, detail ${detail.episodes.length} eps, browse ${browse.items.length}, feed ${feed.cards.length}`);
